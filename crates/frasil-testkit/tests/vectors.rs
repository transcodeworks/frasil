#[test]
fn all_vector_files_load() {
    let files = vectors::load_all().unwrap_or_else(|error| panic!("{error}"));
    assert_eq!(files.len(), 26);
    let on_disk: Vec<String> = std::fs::read_dir(frasil_testkit::vectors_dir())
        .unwrap()
        .map(|entry| entry.unwrap().file_name().into_string().unwrap())
        .filter(|name| name.ends_with(".json"))
        .collect();
    assert_eq!(on_disk.len(), FILES.len(), "{on_disk:?}");
    for name in &on_disk {
        assert!(FILES.contains(&name.as_str()), "{name} is not listed");
    }
}

#[test]
fn each_file_holds_its_families() {
    for (name, expected) in FAMILIES {
        let file = VectorFile::load(name).unwrap_or_else(|error| panic!("{error}"));
        let mut sorted = expected.to_vec();
        sorted.sort_unstable();
        assert_eq!(file.family_names(), sorted, "{name}");
        for family in expected {
            assert!(file.family(family).is_ok(), "{name} {family}");
        }
    }
    let listed: Vec<&str> = FAMILIES.iter().map(|(name, _)| *name).collect();
    assert_eq!(listed, FILES);
}

#[test]
fn each_file_names_its_document() {
    for name in FILES {
        let file = VectorFile::load(name).unwrap();
        if let Some(specification) = file.metadata("specification") {
            let document = name.replace(".json", ".md");
            assert_eq!(specification.as_str(), Some(document.as_str()), "{name}");
        }
    }
}
