#!/usr/bin/env bash
# Build the JavaScript package (packages/frasil) from a clean state and test it:
# type checks; unit tests with Vitest in Node.js; the scenarios against
# frasil-relay and the CSP check in Chromium and WebKit with Playwright; size
# budgets; the packed package (publint, attw); unused code (knip); and lint.
#
# Installs nothing system-wide. wasm-bindgen must be the version of wasm-bindgen
# in Cargo.lock: the one on the PATH if it is, otherwise one installed with
# `cargo install` into target/wasm-tools. JavaScript tools come from the pnpm
# lockfile. Playwright's browsers must be installed already, WebKit included:
# pnpm --dir packages/frasil exec playwright install chromium webkit
#
#   scripts/check-js.sh                      Chromium and WebKit
#   scripts/check-js.sh --engines chromium   Chromium only
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

engines="chromium,webkit"
while [ $# -gt 0 ]; do
  case "$1" in
    --engines)
      engines="${2:?--engines takes a comma-separated list}"
      shift 2
      ;;
    -h | --help)
      sed -n '3,15p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "check-js: unknown argument $1 (try --help)" >&2
      exit 2
      ;;
  esac
done

fail() {
  echo "check-js: $*" >&2
  exit 1
}

target=wasm32-unknown-unknown
package=packages/frasil

command -v cargo >/dev/null || fail "cargo is not installed; see https://rustup.rs"
command -v node >/dev/null || fail "Node.js is not installed; the package needs Node.js 20 or later"
command -v pnpm >/dev/null || fail "pnpm is not installed; see the packageManager field of package.json"
node_major="$(node -p 'process.versions.node.split(".")[0]')"
[ "$node_major" -ge 20 ] || fail "Node.js $(node --version) is too old; use 20 or later"
sysroot="$(rustc --print sysroot)"
[ -d "$sysroot/lib/rustlib/$target" ] ||
  fail "the Rust standard library for $target is not installed; run: rustup target add $target"

# The glue must be generated by the wasm-bindgen the module links, exactly.
version="$(awk '/^name = "wasm-bindgen"$/ { getline; gsub(/version = |"/, ""); print; exit }' Cargo.lock)"
[ -n "$version" ] || fail "no wasm-bindgen in Cargo.lock"
bindgen="$(command -v wasm-bindgen || true)"
if [ -z "$bindgen" ] || [ "$("$bindgen" --version | awk '{ print $2 }')" != "$version" ]; then
  tools="$root/target/wasm-tools"
  bindgen="$tools/bin/wasm-bindgen"
  if [ ! -x "$bindgen" ] || [ "$("$bindgen" --version | awk '{ print $2 }')" != "$version" ]; then
    echo "check-js: installing wasm-bindgen-cli $version into target/wasm-tools"
    cargo install --quiet --locked --force --root "$tools" wasm-bindgen-cli --version "$version"
  fi
fi
export WASM_BINDGEN="$bindgen"

echo "check-js: installing JavaScript dependencies from the lockfile"
pnpm install --frozen-lockfile

echo "check-js: building $package from a clean state"
rm -rf "$package/dist" "$package/src/wasm"
pnpm --dir "$package" build

echo "check-js: type-checking"
pnpm --dir "$package" typecheck

echo "check-js: unit tests (Node.js $(node --version))"
pnpm --dir "$package" test

echo "check-js: scenarios and the policy check in $engines, against frasil-relay"
FRASIL_TEST_ENGINES="$engines" pnpm --dir "$package" test:binding

echo "check-js: sizes"
pnpm --dir "$package" size

# The package as npm would receive it: its manifest (publint), and the types
# each entry resolves to (Are the Types Wrong, for an ESM-only package).
echo "check-js: the packed package"
pnpm --dir "$package" check:package

echo "check-js: unused files and dependencies"
pnpm --dir "$package" knip

echo "check-js: lint"
pnpm --dir "$package" lint
