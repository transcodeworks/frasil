"""Normalises the glue UniFFI generates (scripts/bindings.sh): a header line
that says how to regenerate it, no trailing spaces, and, in Swift, the
`Sendable` bounds that Swift 6's strict concurrency asks of UniFFI 0.31's
async callback helpers."""

import re
import sys
from pathlib import Path


def swift(text: str) -> str:
    text = text.replace("private func uniffiTraitInterfaceCallAsync<T>(",
                        "private func uniffiTraitInterfaceCallAsync<T: Sendable>(")
    text = text.replace("private func uniffiTraitInterfaceCallAsyncWithError<T, E>(",
                        "private func uniffiTraitInterfaceCallAsyncWithError<T: Sendable, E>(")
    text = text.replace("let uniffiHandleSuccess = {", "let uniffiHandleSuccess = { @Sendable")
    text = text.replace("let uniffiHandleError = {", "let uniffiHandleError = { @Sendable")
    return re.sub(r"(private func uniffiTraitInterfaceCallAsync(?:WithError)?[\s\S]*?\n\) \{)",
                  lambda m: m[0].replace("@escaping", "@escaping @Sendable"), text)


def main(out: str) -> None:
    for path in Path(out).rglob("*"):
        if path.suffix not in (".swift", ".kt", ".h"):
            continue
        text = path.read_text()
        if path.suffix == ".swift":
            text = swift(text)
        header = "// Generated by UniFFI 0.31.0 from crates/frasil-uniffi. Regenerate with scripts/bindings.sh.\n"
        text = header + "\n".join(line.rstrip() for line in text.splitlines()).rstrip() + "\n"
        path.write_text(text)


if __name__ == "__main__":
    main(sys.argv[1])
